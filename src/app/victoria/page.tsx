function TranscriptTimeline({
  entries,
  repName,
  prospectName,
}: {
  entries: TranscriptFeedEntry[];
  repName?: string;
  prospectName?: string;
}) {
  const bottomRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [entries.length]);

  const formatElapsed = (s: number) => {
    const m = Math.floor(s / 60).toString().padStart(2, "0");
    const sec = (s % 60).toString().padStart(2, "0");
    return `${m}:${sec}`;
  };

  if (entries.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center h-full text-center">
        <Radio size={20} className="mb-2 opacity-20" style={{ color: "var(--t-muted)" }} />
        <p className="text-[11px]" style={{ color: "var(--t-muted)" }}>
          Transcript will appear here as the call unfolds.
        </p>
        <p className="text-[10px] mt-1" style={{ color: "var(--t-dim)" }}>
          Start speaking — events highlight inline in real time.
        </p>
      </div>
    );
  }

  return (
    <div className="space-y-0">
      {entries.map((entry) => {
        const isRep = entry.speaker === "rep";
        return (
          <div
            key={entry.id}
            className="flex gap-2.5 py-2.5"
            style={{ borderBottom: "1px solid rgba(255,255,255,0.04)" }}
          >
            {/* Elapsed time */}
            <span
              className="text-[9px] font-mono w-8 flex-shrink-0 text-right mt-0.5 leading-none"
              style={{ color: "var(--t-dim)" }}
            >
              {formatElapsed(entry.elapsed_s)}
            </span>

            {/* Speaker badge — shows real name when available */}
            <span
              className="text-[8px] font-bold px-1.5 py-0.5 rounded flex-shrink-0 h-fit leading-tight whitespace-nowrap"
              style={{
                backgroundColor: isRep ? "rgba(107,114,128,0.15)" : "rgba(34,197,94,0.1)",
                color: isRep ? "#9ca3af" : "#22c55e",
                border: `1px solid ${isRep ? "rgba(107,114,128,0.2)" : "rgba(34,197,94,0.2)"}`,
              }}
              title={isRep ? "Sales rep" : "Prospect"}
            >
              {isRep
                ? (repName ? repName.split(" ")[0].toUpperCase() : "REP")
                : (prospectName ? prospectName.split(" ")[0].toUpperCase() : "PRO")}
            </span>

            {/* Content */}
            <div className="flex-1 min-w-0 space-y-1.5">
              <p
                className="text-[12px] leading-relaxed"
                style={{ color: isRep ? "var(--t-muted)" : "var(--t-text)" }}
              >
                {entry.text}
              </p>

              {/* Inline event highlights */}
              {entry.events.length > 0 && (
                <div className="flex flex-wrap gap-1">
                  {entry.events.slice(0, 5).map((evt) => {
                    const meta = TIMELINE_EVENT_META[evt.event_type] ?? {
                      icon: "•", color: "#6b7280", label: evt.event_type,
                    };
                    return (
                      <span
                        key={evt.id}
                        className="text-[8px] font-bold px-1.5 py-0.5 rounded-full cursor-default"
                        style={{
                          backgroundColor: `${meta.color}14`,
                          color: meta.color,
                          border: `1px solid ${meta.color}28`,
                        }}
                        title={`${evt.title}: ${evt.description}`}
                      >
                        {meta.icon} {meta.label}
                      </span>
                    );
                  })}
                </div>
              )}
            </div>
          </div>
        );
      })}
      <div ref={bottomRef} />
    </div>
  );
}


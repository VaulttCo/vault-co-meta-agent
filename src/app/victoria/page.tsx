function ScoreBar({
  label, score, color, momentum,
}: {
  label: string;
  score: number;
  color: string;
  momentum?: MomentumDirection;
}) {
  const arrow = momentum === "improving" ? "↑" : momentum === "declining" ? "↓" : momentum === "stable" ? "→" : null;
  const arrowColor = momentum === "improving" ? "#22c55e" : momentum === "declining" ? "#ef4444" : "#374151";

  return (
    <div className="space-y-1">
      <div className="flex items-center justify-between">
        <span className="text-[11px]" style={{ color: "var(--t-muted)" }}>{label}</span>
        <div className="flex items-center gap-1">
          {arrow && (
            <span className="text-[10px] font-bold tabular-nums" style={{ color: arrowColor }}>{arrow}</span>
          )}
          <span className="text-[11px] font-bold tabular-nums" style={{ color }}>{score}</span>
        </div>
      </div>
      <div className="h-1.5 rounded-full" style={{ backgroundColor: "rgba(255,255,255,0.06)" }}>
        <div
          className="h-1.5 rounded-full transition-all duration-700"
          style={{ width: `${score}%`, backgroundColor: color }}
        />
      </div>
    </div>
  );
}

